#!/usr/bin/env python3
"""Paper-grade ASTRO benchmark wrapper.

This file intentionally leaves ``scripts/astro_lab.py`` untouched so historical
results retain their exact provenance. It patches only the confirmatory paper
campaign:

1. schedules every learning-rate field actually consumed by an update, including
   Muon-family auxiliary AdamW rates, with one common warmup/cosine factor;
2. uses standard GPT-style decay routing for *all* compared optimizers: 2-D
   weights (including embeddings/head) decay, vectors/biases/norm parameters do
   not; this removes another silent baseline/recipe difference;
3. pins FineWeb-Edu to v1.0.0 and uses one fixed shared token cache independent
   of the requested step budget;
4. adds a single-GPU AdaMuon matrix rule faithful to the authors' public GPT-2
   implementation: sign before Newton-Schulz, elementwise post-polar second
   moment without bias correction, and 0.2-RMS alignment. The non-matrix AdamW
   path is standardized to this campaign's common routing/scheduling protocol;
5. adds ASTRO-v2-NoSplit and ASTRO-v2-Blockwise controls. The latter performs
   row adaptation and Frobenius restoration independently inside each Q/K/V
   block, while ASTRO-v2 recombines the independently polarised blocks before
   one global redistribution/restoration. This isolates ASTRO's candidate novel
   contribution;
6. stores a code+environment protocol signature in every state file and refuses
   to reuse results generated by a different campaign implementation or Python /
   PyTorch / Transformers / Datasets environment.

Run exactly like ``astro_lab.py``. Example:

    python scripts/paper_campaign.py --mode scaling --sizes 124M --steps 900 \
      --optimizers muon normuon adamuon_ref astro_v2 --trials 5 --seeds 5 \
      --work-dir /content/drive/MyDrive/astro/paper_main --stop-after 5

Record the printed campaign fingerprint with every paper result.
"""

