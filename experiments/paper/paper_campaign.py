def paper_groups(model, optimizer_name: str, config: dict[str, float]) -> list[dict]:
    """One routing/decay policy for every optimizer in the campaign.

    Hidden 2-D operators use the matrix path for Muon-family optimizers.
    Embeddings / tied LM head remain on the auxiliary path but receive weight
    decay. Vectors (biases, LayerNorm gains/shifts) remain on the auxiliary path
    with zero weight decay. This is the standard GPT split used by nanoGPT and
    by AdaMuon's public GPT-2 integration.

    ASTRO alone may split a fused QKV operator into semantic blocks because that
    split is one of the algorithmic mechanisms being tested. Muon-family
    baselines receive the same tensor as one matrix.
    """
    try:
        from transformers.pytorch_utils import Conv1D
    except ImportError:  # pragma: no cover
        Conv1D = ()  # type: ignore[assignment]

    excluded, transposed_ids, fused_ids = set(), set(), set()
    for module in model.modules():
        if isinstance(module, torch.nn.Embedding):
            excluded.add(id(module.weight))
    output = getattr(model, "lm_head", None)
    if output is not None:
        excluded.add(id(output.weight))

    for name, module in model.named_modules():
        weight = getattr(module, "weight", None)
        if weight is None or weight.ndim != 2:
            continue
        if Conv1D and isinstance(module, Conv1D):
            transposed_ids.add(id(weight))
        if name.endswith("c_attn"):
            fused_ids.add(id(weight))

    width = getattr(model.config, "n_embd", None)
    wd = float(config.get("weight_decay", 0.0))
    nodecay_scalar: list[torch.nn.Parameter] = []
    decay_scalar: list[torch.nn.Parameter] = []
    fused: list[torch.nn.Parameter] = []
    spectral_buckets: dict[bool, list[torch.nn.Parameter]] = {}

    for param in model.parameters():
        if param.ndim < 2:
            nodecay_scalar.append(param)
        elif id(param) in excluded:
            decay_scalar.append(param)
        elif id(param) in fused_ids and width is not None:
            fused.append(param)
        else:
            spectral_buckets.setdefault(id(param) in transposed_ids, []).append(param)

    groups: list[dict] = []
    if nodecay_scalar:
        groups.append(
            {
                "params": nodecay_scalar,
                "spectral": False,
                "transposed": False,
                "weight_decay": 0.0,
            }
        )
    if decay_scalar:
        groups.append(
            {
                "params": decay_scalar,
                "spectral": False,
                "transposed": False,
                "weight_decay": wd,
            }
        )
    for transposed, params in spectral_buckets.items():
        groups.append(
            {
                "params": params,
                "spectral": True,
                "transposed": transposed,
                "weight_decay": wd,
            }
        )
    if fused:
        groups.append(
            {
                "params": fused,
                "spectral": True,
                "transposed": all(id(p) in transposed_ids for p in fused),
                "blocks": (width, width, width) if optimizer_name == "astro" else None,
                "weight_decay": wd,
            }
        )
    return groups


