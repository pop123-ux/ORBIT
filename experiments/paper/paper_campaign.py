def paper_load_state() -> dict:
    state = ORIGINAL_LOAD_STATE()
    current = protocol_record()
    previous = state.get("paper_protocol")
    has_measurements = any(state.get(section) for section in ("runs", "trials", "tuned"))

    if previous is None and has_measurements:
        raise SystemExit(
            "this workdir contains measurements without a paper_campaign protocol "
            "signature. Use a fresh workdir; historical astro_lab results must not "
            "be silently mixed into the confirmatory campaign."
        )
    if previous is not None:
        if previous.get("code_digest") != current["code_digest"]:
            raise SystemExit(
                "paper_campaign code fingerprint changed since this state was "
                "created. Do not mix implementations in one table; use a new "
                "workdir or deliberately rerun the entire affected campaign."
            )
        if previous.get("environment") != current["environment"]:
            raise SystemExit(
                "paper_campaign Python/package environment changed since this "
                f"state was created. recorded={previous.get('environment')} "
                f"current={current['environment']}. Reinstall the recorded "
                "versions before resuming rather than mixing environments."
            )
        for field in ("fineweb_revision", "validation_tokens", "training_token_pool"):
            if previous.get(field) != current[field]:
                raise SystemExit(
                    f"paper protocol field {field!r} changed: "
                    f"{previous.get(field)!r} -> {current[field]!r}. Use a fresh workdir."
                )

    state["paper_protocol"] = current
    return state


def paper_save_state(state: dict) -> None:
    state["paper_protocol"] = protocol_record()
    ORIGINAL_SAVE_STATE(state)


def paper_announce(args) -> None:
    record = protocol_record()
    print(
        f"paper_campaign {record['code_digest'][:12]} "
        f"(astro_lab + paper wrapper)",
        flush=True,
    )
    print(
        f"protocol FineWeb-Edu@{FINEWEB_REVISION}; shared cache {SHARED_CACHE}; "
        f"validation {lab.VALIDATION_TOKENS:,}; training pool {TRAIN_TOKENS:,}",
        flush=True,
    )
    print(
        "environment "
        + " ".join(f"{k}={v}" for k, v in record["environment"].items()),
        flush=True,
    )
    if args.config:
        return
    unknown = set(args.pin) - {
        k for n in args.optimizers for k in paper_space_for(n)
    }
    if unknown:
        raise SystemExit(
            f"--pin {sorted(unknown)[0]!r} is not tuned by any requested optimizer"
        )
    print("search space per optimizer (pinned values marked *):", flush=True)
    for name in args.optimizers:
        terms = []
        for key, (lo, hi) in paper_space_for(name).items():
            terms.append(
                f"{key}=*{args.pin[key]:g}"
                if key in args.pin
                else f"{key}=[{lo:g},{hi:g}]"
            )
        print(f"  {name:20s} " + "  ".join(terms), flush=True)


