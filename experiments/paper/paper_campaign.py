FINEWEB_REVISION = "v1.0.0"
TRAIN_TOKENS = 12_000_000
TOTAL_TOKENS = lab.VALIDATION_TOKENS + TRAIN_TOKENS
SHARED_CACHE = Path(
    os.environ.get(
        "ASTRO_PAPER_TOKEN_CACHE",
        "/content/drive/MyDrive/astro/paper_shared/fineweb_edu_v1.0.0_12p4m.pt",
    )
)


def campaign_digest() -> str:
    wrapper = Path(__file__).resolve().read_bytes()
    base = Path(lab.__file__).resolve().read_bytes()
    return hashlib.sha256(wrapper + b"\0" + base).hexdigest()


def current_environment() -> dict[str, str]:
    import datasets
    import transformers

    return {
        "python": platform.python_version(),
        "torch": torch.__version__,
        "torch_cuda": str(torch.version.cuda),
        "transformers": transformers.__version__,
        "datasets": datasets.__version__,
    }


def protocol_record() -> dict:
    return {
        "code_digest": campaign_digest(),
        "fineweb_revision": FINEWEB_REVISION,
        "validation_tokens": lab.VALIDATION_TOKENS,
        "training_token_pool": TRAIN_TOKENS,
        "shared_cache": str(SHARED_CACHE),
        "environment": current_environment(),
    }


