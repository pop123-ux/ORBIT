class PublishedAdaMuon(torch.optim.Optimizer):
    """AdaMuon matrix rule plus the campaign's common auxiliary AdamW path.

    The public AdaMuon implementation computes Nesterov momentum, applies sign,
    orthogonalises that sign matrix, tracks an elementwise second moment of the
    orthogonalised update with the same 0.95 coefficient, divides without bias
    correction, then RMS-aligns the result to 0.2. Its GPT-2 code trains the
    remaining parameters with a separate AdamW optimizer.

    The public distributed implementation stores the NS communication buffer in
    bfloat16. T4 (sm_75) lacks native BF16 tensor-core support, so this campaign
    uses the same float32 Newton-Schulz kernel as its Muon-family baselines. This
    is a stated numerical/hardware accommodation, not an algorithmic change.
    """

    def __init__(
        self,
        groups,
        *,
        lr: float,
        adamw_lr: float,
        weight_decay: float,
        momentum: float = 0.95,
        nesterov: bool = True,
        ns_steps: int = 5,
        eps: float = 1e-8,
        adamw_betas: tuple[float, float] = (0.9, 0.95),
    ) -> None:
        super().__init__(
            groups,
            dict(
                lr=lr,
                adamw_lr=adamw_lr,
                weight_decay=weight_decay,
                momentum=momentum,
                nesterov=nesterov,
                ns_steps=ns_steps,
                eps=eps,
                betas=adamw_betas,
            ),
        )

    @torch.no_grad()
    def step(self):  # type: ignore[override]
        for group in self.param_groups:
            for param in group["params"]:
                if param.grad is None:
                    continue

                grad = param.grad
                operator = grad.T if group.get("transposed") else grad
                state = self.state[param]
                if not state:
                    state["step"] = 0
                    state["momentum"] = torch.zeros_like(operator)
                    state["variance"] = torch.zeros_like(operator)
                state["step"] += 1

                if group["spectral"]:
                    momentum = state["momentum"].mul_(group["momentum"]).add_(operator)
                    update = (
                        operator.add(momentum, alpha=group["momentum"])
                        if group["nesterov"]
                        else momentum
                    )
                    update = lab.newton_schulz(
                        torch.sign(update), steps=group["ns_steps"]
                    )

                    variance = state["variance"]
                    beta = group["momentum"]
                    variance.mul_(beta).addcmul_(update, update, value=1.0 - beta)
                    update = update / variance.sqrt().add_(group["eps"])

                    rms_scale = (
                        0.2
                        * math.sqrt(update.size(0) * update.size(1))
                        / update.norm().clamp_min(group["eps"])
                    )
                    update = (update * rms_scale).to(param.dtype)
                    if group.get("transposed"):
                        update = update.T

                    if group["weight_decay"]:
                        param.mul_(1.0 - group["lr"] * group["weight_decay"])
                    param.add_(update, alpha=-group["lr"])
                else:
                    beta1, beta2 = group["betas"]
                    step = state["step"]
                    momentum = state["momentum"].mul_(beta1).add_(grad, alpha=1 - beta1)
                    variance = state["variance"]
                    variance.mul_(beta2).addcmul_(grad, grad, value=1 - beta2)
                    update = (momentum / (1 - beta1**step)) / (
                        (variance / (1 - beta2**step)).sqrt().add_(group["eps"])
                    )
                    if group["weight_decay"]:
                        param.mul_(1.0 - group["adamw_lr"] * group["weight_decay"])
                    param.add_(update, alpha=-group["adamw_lr"])


