def paper_space_for(name: str) -> dict[str, tuple[float, float]]:
    if name == "adamuon_ref":
        # The official GPT-2 experiments use a much smaller LR than vanilla
        # Muon because AdaMuon's 0.2-RMS alignment changes the update unit. Keep
        # that natural LR range while giving the auxiliary AdamW path the same
        # independently tunable multiplier that every other matrix optimizer
        # receives in this harness.
        return {
            "lr": lab.ADAM_LR,
            "weight_decay": (1e-3, 3e-1),
            "scalar_lr_mult": lab.SCALAR_MULT,
        }
    return ORIGINAL_SPACE_FOR(name)


def paper_build_optimizer(name: str, model, config: dict[str, float]):
    if name not in lab.known_optimizers():
        raise SystemExit(
            f"unknown optimizer {name!r}. available: {', '.join(lab.known_optimizers())}"
        )

    scalar = config.get("scalar_lr_mult", 1.0)

    if name == "adamw":
        routed = paper_groups(model, "muon", config)
        groups = [
            {"params": g["params"], "weight_decay": g["weight_decay"]}
            for g in routed
            if g["params"]
        ]
        return torch.optim.AdamW(
            groups,
            lr=config["lr"],
            betas=(0.9, config.get("beta2", 0.95)),
        )

    if name in {"muon", "normuon", "adamuon"}:
        groups = paper_groups(model, "muon", config)
        cls = {"muon": lab.Muon, "normuon": lab.NorMuon, "adamuon": lab.AdaMuon}[name]
        return cls(
            groups,
            lr=config["lr"],
            adamw_lr=config["lr"] * scalar,
            weight_decay=config["weight_decay"],
        )

    if name == "adamuon_ref":
        groups = paper_groups(model, "muon", config)
        return PublishedAdaMuon(
            groups,
            lr=config["lr"],
            adamw_lr=config["lr"] * scalar,
            weight_decay=config["weight_decay"],
            momentum=0.95,
        )

    overrides = dict(lab.VARIANTS.get(name, {}))
    split = overrides.pop("split", True)
    groups = paper_groups(model, "astro" if split else "muon", config)

    if name == "astro_v2_blockwise":
        return AstroV2Blockwise(
            groups,
            lr=config["lr"],
            scalar_lr_mult=scalar,
            weight_decay=config["weight_decay"],
            **overrides,
        )

    return lab.Astro(
        groups,
        lr=config["lr"],
        scalar_lr_mult=scalar,
        weight_decay=config["weight_decay"],
        **overrides,
    )


